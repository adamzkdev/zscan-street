// node shots/_gtamosaic.mjs [URL] [OUT]: the garage's mosaic of the 10,000 (src/gta/mosaic.ts): all, filtered, picked
import puppeteer from "puppeteer-core";
const [URL = "http://localhost:3061/?debug&gta&theme=day", OUT = "shots/gta/mosaic"] = process.argv.slice(2);
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", protocolTimeout: 600000, args: ["--use-angle=metal", "--ignore-gpu-blocklist"], defaultViewport: { width: 1600, height: 900 } });
const p = await b.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push("pageerror " + e.message));
await p.goto(URL);
await p.waitForFunction(() => window.__streetUp && window.street?.gta?.garage?.open, { timeout: 240000, polling: 300 });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(1500);
// (the front end's line-up: its "All 10,000")
await p.evaluate(() => street.gta.front.select());
await sleep(1500);
await p.click(".gf-tools [data-do=all]");
await p.waitForFunction(() => document.querySelector(".gm-wait")?.style.display === "none", { timeout: 60000, polling: 300 });
await sleep(800);
await p.screenshot({ path: `${OUT}-1-all.png` });
await p.click('[data-band="1"]');
await sleep(400);
await p.screenshot({ path: `${OUT}-2-epic.png` });
const chip = await p.$('[data-t="4"]');
if (chip) await chip.click();
await sleep(400);
await p.mouse.move(700, 300);
await sleep(300);
await p.screenshot({ path: `${OUT}-3-trait.png` });
console.log(await p.evaluate(() => document.querySelector(".gm-count").textContent));
await p.mouse.click(700, 300);
await sleep(1500);
await p.screenshot({ path: `${OUT}-4-picked.png` });
console.log(await p.evaluate(() => JSON.stringify({ id: document.querySelector(".gf-cname em")?.textContent, mosaic: document.querySelector(".gg-mosaic").classList.contains("on") })));
console.log("errors", errs.length, errs.slice(0, 5).join("\n"));
await b.close();
