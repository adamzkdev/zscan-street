import puppeteer from "puppeteer-core";
const theme = process.argv[2] ?? "night";
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--use-angle=metal", "--ignore-gpu-blocklist"], defaultViewport: { width: 1440, height: 860 } });
const p = await b.newPage();
const logs = [];
p.on("console", (m) => m.type() === "error" && logs.push(m.text()));
p.on("pageerror", (e) => logs.push(`[pageerror] ${e.message}`));
await p.goto(`http://localhost:3007/?debug&theme=${theme}`);
await new Promise((r) => setTimeout(r, 9000));
await p.evaluate(() => street.lookIn("downtown"));
await new Promise((r) => setTimeout(r, 3500));
await p.screenshot({ path: `shots/shop-${theme}-a.png` });
await p.evaluate(() => { const m = street.shelf.meshes[0]; street.hud.showBlock(m.userData.block); });
await new Promise((r) => setTimeout(r, 2500));
await p.screenshot({ path: `shots/shop-${theme}-b.png` });
await p.evaluate(() => { street.rig.setMode("live"); street.venues.show("cards"); });
await new Promise((r) => setTimeout(r, 3500));
await p.screenshot({ path: `shots/shop-${theme}-c.png` });
await p.evaluate(() => street.venues.show("bank"));
await new Promise((r) => setTimeout(r, 1000));
await p.screenshot({ path: `shots/shop-${theme}-d.png` });
console.log(logs.join("\n"));
await b.close();
