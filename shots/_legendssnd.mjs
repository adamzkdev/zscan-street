import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--autoplay-policy=no-user-gesture-required"] });
const p = await b.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => (m.type() === "error" || m.type() === "warn") && errs.push(m.text().slice(0, 200)));
await p.goto("http://localhost:3071/tablelab.html");
const r = await p.evaluate(async () => {
  const kit = await import("/src/party/kit.ts");
  const { LegendsSound } = await import("/src/tables/legends/sound.ts");
  const s = new LegendsSound();
  const has = !!kit.sound();
  s.music("menu");
  s.draw(); s.play(); s.land(true); s.attack(); s.hit(3); s.hit(7); s.heroHit(); s.die();
  await new Promise((r) => setTimeout(r, 2500));
  s.draw(); s.halo(); s.freeze(); s.spell(); s.bolt(); s.heal(); s.buff(); s.secret(); s.reveal(); s.turn(); s.end(); s.error(); s.coin(); s.packOpen(); s.flip("legendary"); s.ui("click"); s.ui("hover");
  s.startDrone();
  await new Promise((r) => setTimeout(r, 3000));
  const st = { has, playing: s["playing"]?.key ?? null, ready: s["ready"].size, ac: s["ac"]?.state };
  s.music("tension");
  await new Promise((r) => setTimeout(r, 3000));
  st.after = s["playing"]?.key ?? null;
  s.win();
  await new Promise((r) => setTimeout(r, 800));
  st.afterWin = s["playing"]?.key ?? null;
  s.muted = true; s.muted = false; s.stopDrone();
  return st;
});
console.log(JSON.stringify(r));
console.log("errors:", errs.length ? errs.join("\n") : "none");
await b.close();
