// node shots/_legendsfront.mjs [port] [prefix]: ZK LEGENDS' front end (menus.ts): menu, play, collection, sheet, deck editor, packs, rules, settings
import puppeteer from "puppeteer-core";
const PORT = process.argv[2] || "3075";
const OUT = process.argv[3] || "shots/legends/front";
const W = +(process.env.W || 1600), H = +(process.env.H || 900);
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", protocolTimeout: 600000, args: ["--use-angle=metal", "--ignore-gpu-blocklist"], defaultViewport: { width: W, height: H, isMobile: !!process.env.MOBILE, hasTouch: !!process.env.MOBILE } });
const p = await b.newPage();
const errs = [];
p.on("console", (m) => /error/.test(m.type()) && errs.push(m.text().slice(0, 300)));
p.on("pageerror", (e) => errs.push("pageerror " + e.message + " " + (e.stack || "").split("\n")[1]));
p.on("response", (r) => r.status() >= 400 && !/items\/\d+\/image/.test(r.url()) && errs.push(`${r.status()} ${r.url().slice(0, 140)}`));
await p.evaluateOnNewDocument(() => {
  window.WebSocket = class { constructor() {} send() {} close() {} addEventListener() {} };
  if (location.search.includes("reset")) localStorage.removeItem("street.legends.collection");
});
await p.goto(`http://localhost:${PORT}/tablelab.html?t=legends&seed=12&stake=100&reset`);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (n) => { await p.screenshot({ path: `${OUT}-${n}.png` }); console.log("shot", n); };
const click = (sel) => p.evaluate((s) => { const e = document.querySelector(s); if (e) e.click(); return !!e; }, sel);
await sleep(5500);
await shot("01-menu");
if (process.env.ONLY === "menu") { console.log("errors:", errs.length ? errs.join("\n") : "none"); await b.close(); process.exit(0); }
await click('.zkf-item[data-k="play"]');
await sleep(2200);
await shot("02-play");
await p.keyboard.press("ArrowRight");
await sleep(500);
await shot("03-play-next");
await p.keyboard.press("Escape");
await sleep(800);
await click('.zkf-item[data-k="coll"]');
await sleep(3500);
await shot("04-coll");
await click('.zkf-chips[data-f="tier"] button[data-v="legendary"]');
await sleep(2500);
await shot("05-coll-legend");
await p.evaluate(() => document.querySelector(".zkf-tile")?.click());
await sleep(1500);
await shot("06-sheet");
// search a number
await p.evaluate(() => { const i = document.querySelector(".zkf-search"); i.value = "#4071"; i.dispatchEvent(new Event("input")); });
await sleep(1200);
await p.evaluate(() => document.querySelector(".zkf-tile")?.click());
await sleep(1200);
await shot("07-search");
// classics + a new deck
await p.evaluate(() => { const i = document.querySelector(".zkf-search"); i.value = ""; i.dispatchEvent(new Event("input")); });
await click('.zkf-chips[data-f="tier"] button[data-v="legendary"]');
await click('.zkf-seg[data-f="set"] button[data-v="classics"]');
await sleep(800);
await click(".zkf-newdeck");
await sleep(600);
await shot("08-pools");
await click('[data-pool="orchard"]');
await sleep(1500);
await click('[data-do="fill"]');
await sleep(1500);
await shot("09-deck");
await click('[data-do="save"]');
await sleep(800);
await p.keyboard.press("Escape");
await sleep(800);
await click('.zkf-item[data-k="packs"]');
await sleep(2000);
await shot("10-packs");
await click('[data-do="open"]');
await sleep(2600);
await shot("11-opening");
for (let i = 0; i < 5; i++) { await p.keyboard.press("Enter"); await sleep(700); }
await sleep(800);
await shot("12-opened");
await p.keyboard.press("Enter");
await sleep(600);
await p.keyboard.press("Escape");
await sleep(800);
await click('.zkf-item[data-k="rules"]');
await sleep(800);
await click('.zkf-ptabs [data-t="1"]');
await sleep(400);
await shot("13-rules");
await p.keyboard.press("Escape");
await sleep(400);
await click('.zkf-item[data-k="settings"]');
await sleep(600);
await shot("14-settings");
await p.keyboard.press("Escape");
await sleep(300);
// into a duel
await click('.zkf-item[data-k="play"]');
await sleep(1500);
await p.keyboard.press("Enter");
await sleep(4000);
await shot("15-duel");
console.log("errors:", errs.length ? [...new Set(errs)].join("\n") : "none");
await b.close();
