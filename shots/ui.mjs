import puppeteer from "puppeteer-core";
const theme = process.argv[2] ?? "day";
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--use-angle=metal", "--ignore-gpu-blocklist"], defaultViewport: { width: Number(process.argv[3] ?? 1600), height: Number(process.argv[4] ?? 900) } });
const p = await b.newPage();
const logs = [];
p.on("console", (m) => m.type() === "error" && logs.push(m.text()));
p.on("pageerror", (e) => logs.push(`[pageerror] ${e.message}`));
await p.goto(`http://localhost:3007/?debug&theme=${theme}`);
await new Promise((r) => setTimeout(r, 9000));
await p.screenshot({ path: `shots/ui-${theme}-a.png` });
await p.evaluate(() => {
  const s = [...street.director.snarks].find((x) => x.txs.length && x.root.visible) ?? [...street.director.snarks][0];
  street.select(s);
});
await new Promise((r) => setTimeout(r, 2500));
await p.screenshot({ path: `shots/ui-${theme}-b.png` });
await p.evaluate(() => street.select(null));
await p.click(".strip .bar");
await new Promise((r) => setTimeout(r, 800));
await p.screenshot({ path: `shots/ui-${theme}-c.png` });
console.log(logs.join("\n"));
await b.close();
