import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--use-angle=metal"], defaultViewport: { width: 1440, height: 860 } });
const p = await b.newPage();
const logs = [];
p.on("pageerror", (e) => logs.push(`[pageerror] ${e.message}`));
p.on("console", (m) => m.type() === "error" && logs.push(m.text()));
await p.goto(`http://localhost:3007/?debug&theme=day`);
await new Promise((r) => setTimeout(r, 11000));
await p.evaluate(() => { const v = street.city.venues.find((x) => x.kind === "zsa"); const T = street.rig.controls.target.constructor; street.rig.flyTo(new T(v.door.x, 1, v.door.z + 2), 1.6); });
await new Promise((r) => setTimeout(r, 3500));
await p.screenshot({ path: "shots/zsa-ext.png" });
await p.evaluate(() => street.enter("zsa"));
await new Promise((r) => setTimeout(r, 3500));
await p.screenshot({ path: "shots/zsa-in-a.png" });
await p.evaluate(() => { const I = street.interiors; const V = I.walk.camera.position.constructor; I.walk.place(new V(-1, 0, -4.5), 0.5, 0); });
await new Promise((r) => setTimeout(r, 1500));
await p.screenshot({ path: "shots/zsa-in-b.png" });
console.log(logs.join("\n"));
await b.close();
