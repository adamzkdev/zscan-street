// node shots/_gta.mjs [URL] [OUT]: the game (src/gta): the garage, on foot, at the wheel, the map, the menu
import puppeteer from "puppeteer-core";
const [URL = "http://localhost:3061/?debug&gta&theme=day", OUT = "shots/gta/run"] = process.argv.slice(2);
const W = +(process.env.W || 1600), H = +(process.env.H || 900);
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", protocolTimeout: 600000, args: ["--use-angle=metal", "--ignore-gpu-blocklist"], defaultViewport: { width: W, height: H } });
const p = await b.newPage();
const errs = [];
p.on("console", (m) => /error/.test(m.type()) && errs.push(m.text().slice(0, 300)));
p.on("pageerror", (e) => errs.push("pageerror " + e.message));
p.on("response", (r) => r.status() >= 400 && errs.push(`${r.status()} ${r.url().slice(0, 140)}`));
await p.goto(URL);
await p.waitForFunction(() => window.__streetUp && window.street, { timeout: 240000, polling: 300 });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = async (n) => { await p.screenshot({ path: `${OUT}-${n}.png` }); console.log("shot", n); };
const info = () => p.evaluate(() => { const g = street.gta; const c = g.car; return JSON.stringify({ active: g.active, paused: g.paused, car: c ? { kind: c.kind, v: +(c.speed * 3.6).toFixed(0), x: +c.group.position.x.toFixed(1), z: +c.group.position.z.toFixed(1), yaw: +c.yaw.toFixed(2), gear: c.gear } : null, foot: g.player.pos.toArray().map((v) => +v.toFixed(1)), fps: Math.round(1000 / (street.renderer.info.render.frame ? 16 : 16)) }); });
await sleep(4000);
await shot("01-garage");
await p.keyboard.press("ArrowRight");
await sleep(1200);
await p.keyboard.press("Enter");
await sleep(2500);
await shot("02-foot");
await p.keyboard.press("Enter"); // (the coach card: away)
await p.keyboard.down("KeyW");
await sleep(1500);
await shot("03-run");
await p.keyboard.up("KeyW");
// walk to the GT and get in
await p.evaluate(() => { const g = street.gta; const c = g.parked[0]; if (c) { const q = c.group.position; g.player.place(q.x - 2, 0.2, q.z + 2, 0); } });
await sleep(600);
await shot("04-near-car");
await p.keyboard.press("KeyF");
await sleep(800);
console.log(await info());
await p.keyboard.down("KeyW");
await sleep(2500);
await shot("05-drive");
await p.keyboard.down("ShiftLeft");
await sleep(1500);
await shot("06-nitro");
await p.keyboard.up("ShiftLeft");
await p.keyboard.down("KeyD");
await p.keyboard.down("Space");
await sleep(900);
await shot("07-drift");
await p.keyboard.up("Space");
await p.keyboard.up("KeyD");
await sleep(1500);
await p.keyboard.up("KeyW");
console.log(await info());
await shot("08-cruise");
// the police
await p.evaluate(() => street.gta.heat.raise(2, "test"));
await p.keyboard.down("KeyW");
await sleep(5000);
await shot("08b-chase");
await p.keyboard.up("KeyW");
console.log(await p.evaluate(() => JSON.stringify({ stars: street.gta.heat.stars, cops: street.gta.heat.chasers.map((c) => [Math.round(c.car.group.position.x), Math.round(c.car.group.position.z), Math.round(c.car.speed * 3.6)]) })));
await p.keyboard.press("Tab");
await sleep(900);
await shot("09-map");
await p.keyboard.press("Tab");
await sleep(400);
await p.evaluate(() => street.gta.escape());
await sleep(700);
await shot("10-menu");
await p.evaluate(() => street.gta.escape());
const perf = await p.evaluate(async () => { let n = 0; const t0 = performance.now(); await new Promise((r) => { const f = () => { n++; if (performance.now() - t0 < 3000) requestAnimationFrame(f); else r(); }; requestAnimationFrame(f); }); return (n / ((performance.now() - t0) / 1000)).toFixed(1); });
console.log("fps", perf);
console.log("errors", errs.length, errs.slice(0, 8).join("\n"));
await b.close();
