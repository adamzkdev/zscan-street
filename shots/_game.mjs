// Game layer shots: node shots/_game.mjs [theme] [w h]
// Live page (HUD on): overview, power cut spreading then full, bets panel, citizen card, storm.
import puppeteer from "puppeteer-core";
const theme = process.argv[2] ?? "night";
const w = Number(process.argv[3] ?? 1400);
const h = Number(process.argv[4] ?? 860);
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--use-angle=metal", "--ignore-gpu-blocklist"], defaultViewport: { width: w, height: h } });
const p = await b.newPage();
const logs = [];
p.on("console", (m) => m.type() === "error" && logs.push(m.text()));
p.on("pageerror", (e) => logs.push(`[pageerror] ${e.message}`));
await p.goto(`http://localhost:3007/?debug&theme=${theme}`);
await p.waitForFunction(() => window.street?.game, { timeout: 120000 });
await new Promise((r) => setTimeout(r, 9000));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = (n) => p.screenshot({ path: `shots/game-${theme}-${n}.png` });
await shot("0-city");
await p.evaluate(() => street.game.block(0));
await sleep(3500);
await shot("1-cut-spreading");
await p.evaluate(() => street.game.block(0));
await sleep(8000);
await shot("2-blackout");
await p.click(".bet-btn");
await sleep(400);
await p.evaluate(() => document.querySelector('.betpanel [data-a="bet"][data-m="txs"][data-o="4+"]')?.click());
await p.evaluate(() => document.querySelector('.betpanel [data-a="bet"][data-m="shielded"][data-o="yes"]')?.click());
await sleep(300);
await shot("3-bets");
await p.evaluate(() => street.game.block(6, "shielded"));
await sleep(1200);
await shot("4-settled");
await p.click(".bet-btn");
await p.click(".zchip");
await sleep(300);
await shot("5-card");
await p.click(".zchip");
await p.evaluate(() => street.game.world.setMempool(30));
await sleep(6000);
await shot("6-storm");
console.log(logs.join("\n") || "no errors");
await b.close();
