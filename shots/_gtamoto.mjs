// node shots/_gtamoto.mjs [URL] [OUT]: on the bike (src/gta): mount, ride, lean in a turn, get off
import puppeteer from "puppeteer-core";
const [URL = "http://localhost:3061/?debug&gta=1192&theme=day", OUT = "shots/gta/moto"] = process.argv.slice(2);
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", protocolTimeout: 600000, args: ["--use-angle=metal", "--ignore-gpu-blocklist"], defaultViewport: { width: 1600, height: 900 } });
const p = await b.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push("pageerror " + e.message));
await p.goto(URL);
await p.waitForFunction(() => window.__streetUp && window.street?.gta?.solid?.ready, { timeout: 240000, polling: 300 });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await p.evaluate(() => { const g = street.gta; g.hud.coach(-1); const m = g.parked.find((c) => c.kind === "moto"); m.place(-30, 1.5, 0); g.player.place(-31, 0.2, 3.2, -Math.PI / 2); g.cam.behind(-Math.PI / 2, -0.12); });
await sleep(1200);
await p.screenshot({ path: `${OUT}-1-parked.png` });
await p.keyboard.press("KeyF");
await sleep(600);
console.log(await p.evaluate(() => JSON.stringify({ car: street.gta.car?.kind, vis: street.gta.player.group.visible })));
await p.keyboard.down("KeyW");
await sleep(2200);
await p.screenshot({ path: `${OUT}-2-ride.png` });
await p.keyboard.down("KeyA");
await sleep(700);
await p.screenshot({ path: `${OUT}-3-lean.png` });
await p.keyboard.up("KeyA");
await p.keyboard.up("KeyW");
await p.keyboard.down("KeyS");
await sleep(1800);
await p.keyboard.up("KeyS");
await p.keyboard.press("KeyF");
await sleep(800);
await p.screenshot({ path: `${OUT}-4-off.png` });
console.log(await p.evaluate(() => JSON.stringify({ car: street.gta.car?.kind ?? null, vis: street.gta.player.group.visible, body: !!street.gta.player.body?.root.parent && street.gta.player.body.root.parent === street.gta.player.group })));
console.log("errors", errs.length, errs.slice(0, 5).join("\n"));
await b.close();
