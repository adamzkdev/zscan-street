const cache = new Map<string, string>();
/** Icon `name` as an inline SVG (crisp at any size: shape-rendering crispEdges). */
export function pixIcon(name: keyof typeof MAPS | string, cls = "zp-ic") {
  const key = `${name}|${cls}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const m = MAPS[name] ?? MAPS.party;
  let d = "";
  m.forEach((row, y) => {
    // (one rect per run of pixels on a row)
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === "#") w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  const svg = `<svg class="${cls}" viewBox="0 0 12 12" aria-hidden="true" shape-rendering="crispEdges"><path d="${d}" fill="currentColor"/></svg>`;
  cache.set(key, svg);
  return svg;
}
